function touchPool(character) {
  const species = character === 'dog' ? 'dog' : 'cat';
  return [...SHARED.map((text,i)=>({id:`touch-shared-${i+1}`,text})),
    ...SPECIES[species].map((text,i)=>({id:`touch-${species}-${i+1}`,text}))];
}
function pickTouch(config, runtime, rng = Math.random) {
  const recent = runtime.touchRecent || [], pool = touchPool(config.petCharacter);
  const candidates = pool.filter(item => !recent.includes(item.id));
  const item = candidates[Math.min(candidates.length-1, Math.floor(rng()*candidates.length))];
  runtime.touchRecent = [...recent,item.id].slice(-8);
  return renderText(item.text,config);
}
module.exports = {touchPool,pickTouch};
